-- Migration: create the `audit_logs` table — the who/what/when trail.
-- Stay data is personal data, so every mutation **and every sensitive
-- read** (patient locate, stay detail) writes one row here recording
-- the entity kind, the action, the (optional) actor, and a snapshot.

CREATE TABLE IF NOT EXISTS "audit_logs" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "entity" varchar NOT NULL, "entity_pid" uuid NOT NULL, "action" varchar NOT NULL, "actor" varchar NULL, "snapshot" jsonb NULL );

CREATE INDEX IF NOT EXISTS audit_logs_entity ON audit_logs (entity_pid);
