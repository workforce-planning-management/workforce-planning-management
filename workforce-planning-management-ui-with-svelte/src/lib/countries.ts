export interface CountryOption {
  code: string;
  name: string;
  /** Added by the deployer, not in ISO 3166-1. */
  added: boolean;
}

/** The region's name in `locale`, else `fallback`, else the code itself. */
export function countryName(
  code: string,
  locale: string,
  fallback?: string | null,
): string {
  try {
    const name = new Intl.DisplayNames([locale], {
      type: "region",
      fallback: "none",
    }).of(code);
    if (name) return name;
  } catch {
    // An engine without DisplayNames, or a code it refuses: fall through.
  }
  return fallback || code;
}

/**
 * Every country a person may choose, named in `locale` and sorted by that name in that locale: ISO 3166-1, the
 * deployer's added codes, and `held` (a stored value no longer on either list, so it is shown rather than lost).
 */
export function countryOptions(
  locale: string,
  added: ReadonlyArray<{ code: string; name: string | null }> = [],
  held?: string | null,
): CountryOption[] {
  const out = new Map<string, CountryOption>();
  for (const code of ISO_3166_1)
    out.set(code, { code, name: countryName(code, locale), added: false });
  for (const extra of added)
    if (!out.has(extra.code))
      out.set(extra.code, {
        code: extra.code,
        name: countryName(extra.code, locale, extra.name),
        added: true,
      });
  const kept = (held ?? "").trim().toUpperCase();
  if (kept && !out.has(kept))
    out.set(kept, {
      code: kept,
      name: countryName(kept, locale),
      added: false,
    });
  return [...out.values()].sort(
    (a, b) =>
      compareText(a.name, b.name, locale) ||
      compareText(a.code, b.code, locale),
  );
}
