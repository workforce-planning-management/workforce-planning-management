#!/usr/bin/env python3
"""Keep llms.txt and llms.json in step.

llms.json is the source: the entries, the conventions and the status. This script

  * fills `stack.tests` and the migration count from spec/implementation-status.md
    (itself generated by scripts/status.py, so every number is counted, not typed),
  * renders llms.txt from llms.json, and
  * with --check, fails if a listed path does not exist, if a spec topic file is
    listed in neither file, or if either committed file is stale.

    python3 scripts/llms.py          # rewrite llms.json (counts) and llms.txt
    python3 scripts/llms.py --check  # verify only (CI)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JSON_PATH = ROOT / "llms.json"
TXT_PATH = ROOT / "llms.txt"
STATUS = ROOT / "spec" / "implementation-status.md"

HEADINGS = [
    ("specification", "Specification"),
    ("code", "Code"),
    ("agents", "Working agreements"),
    ("operate", "Operate"),
]

# spec files that are generated or are not topics an agent should be sent to
UNLISTED_SPEC = {"spec/implementation-status.md"}


def counts() -> dict[str, int]:
    """The measures in spec/implementation-status.md, by their row label."""
    found = {}
    for line in STATUS.read_text().splitlines():
        m = re.match(r"\| (.+?) \| (\d+) \|", line)
        if m:
            found[m.group(1)] = int(m.group(2))
    return found


def with_counts(data: dict) -> dict:
    c = counts()
    data["stack"]["tests"] = {
        "service_unit_declared": c["Rust unit tests (`#[test]` in `src/`)"],
        "service_request_declared": c["Rust request tests (`tests/requests/`)"],
        "ui_unit_declared": c["Front-end unit tests (`it(` / `test(`)"],
        "ui_e2e_declared": c["Playwright tests (`test(`)"],
        "note": "declared by scripts/status.py (a count of test functions in the files), not what passes; CI reports that",
    }
    data["stack"]["migrations"] = c["Database migrations"]
    data["stack"]["controllers"] = c["Controllers"]
    data["stack"]["pages"] = c["Front-end pages (`+page.svelte`)"]
    return data


def render(data: dict) -> str:
    out = [f"# {data['name']} (WPM)", ""]
    out += [
        "> An open-source, spec-driven, all-in-one HR platform demo: hiring to retirement,",
        "> in Rust (Loco, Axum, SeaORM, PostgreSQL) and SvelteKit (Svelte 5 runes), in 17",
        "> locales. **Demo software — not a production HR or payroll system; synthetic",
        "> data only.** WPM owns the employment relationship and references identities",
        "> (person, worker, organization, course services) by EntityRef URN.",
        "",
        "Start with the specification: it is the single source of truth, and no code",
        "lands without it. A change is a requirement (WPM-R*), a design decision",
        "(WPM-D*), a task (WPM-T*), code and tests.",
        "",
    ]
    st = data["status"]
    s = data["stack"]
    out += [
        f"Status as of {st['as_of']}: tasks {st['tasks_delivered']}; requirements up to "
        f"{st['highest_requirement']}; decisions up to {st['highest_decision']}; "
        f"{s['migrations']} migrations, {s['controllers']} controllers, {s['pages']} pages. "
        "Counts come from [spec/implementation-status.md](spec/implementation-status.md); "
        "they count what is declared, not what passes.",
        "",
    ]
    for key, title in HEADINGS:
        out.append(f"## {title}")
        out.append("")
        for e in data["sections"][key]:
            label = e["path"]
            out.append(f"- [{label}]({e['path']}): {e['description']}")
        out.append("")
    out += ["## Conventions an agent must keep", ""]
    out += [f"- {c}" for c in data["conventions"]]
    out += ["", "## Optional", ""]
    out += [f"- [{e['path']}]({e['path']}): {e['description']}" for e in data["optional"]]
    return "\n".join(out) + "\n"


def problems(data: dict) -> list[str]:
    bad = []
    listed = set()
    for key in list(data["sections"]):
        for e in data["sections"][key]:
            listed.add(e["path"])
            if not (ROOT / e["path"]).exists():
                bad.append(f"missing path: {e['path']}")
    for e in data["optional"]:
        listed.add(e["path"])
        if not (ROOT / e["path"]).exists():
            bad.append(f"missing path: {e['path']}")
    for p in sorted((ROOT / "spec").rglob("*.md")):
        rel = p.relative_to(ROOT).as_posix()
        top = rel.split("/")
        # a topic folder is represented by its index.md or by listing any file inside it
        if rel in UNLISTED_SPEC or rel in listed:
            continue
        if len(top) > 2 and any(x.startswith("/".join(top[:2]) + "/") for x in listed):
            continue
        bad.append(f"spec file in neither llms file: {rel}")
    return bad


def main() -> int:
    check = "--check" in sys.argv
    data = json.loads(JSON_PATH.read_text())
    filled = with_counts(json.loads(JSON_PATH.read_text()))
    new_json = json.dumps(filled, indent=2, ensure_ascii=False) + "\n"
    new_txt = render(filled)
    bad = problems(filled)
    if check:
        if JSON_PATH.read_text() != new_json:
            bad.append("llms.json is stale (run scripts/llms.py)")
        if not TXT_PATH.exists() or TXT_PATH.read_text() != new_txt:
            bad.append("llms.txt is stale (run scripts/llms.py)")
        for line in bad:
            print(line)
        print("llms files ok" if not bad else f"{len(bad)} problem(s)")
        return 1 if bad else 0
    JSON_PATH.write_text(new_json)
    TXT_PATH.write_text(new_txt)
    for line in bad:
        print(line)
    print(f"wrote llms.json and llms.txt ({len(bad)} problem(s) to fix)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
